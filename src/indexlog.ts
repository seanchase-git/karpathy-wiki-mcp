import { promises as fs } from "node:fs";
import path from "node:path";
import { assertNotSymlink, atomicWrite } from "./fsutil.js";
import { extractLinks, linkResolver, PAGE_TYPES, Sandbox, type PageInfo } from "./pages.js";

const TYPE_HEADINGS: Record<string, string> = {
  overview: "Overviews",
  source: "Sources",
  entity: "Entities",
  concept: "Concepts",
  comparison: "Comparisons",
  synthesis: "Syntheses",
};

/** Raw sources cited by at least one `source` page (via `sources:` or a body link). */
export function citedSources(pages: PageInfo[], sourceNames: string[]): Map<string, string[]> {
  const byLower = new Map(sourceNames.map((s) => [s.toLowerCase(), s]));
  // Resolve exactly as Obsidian would, so [[Report]] counts for raw/Report only when no page "Report" exists.
  const resolve = linkResolver(
    pages.map((p) => p.title),
    sourceNames,
  );
  const cited = new Map<string, string[]>();
  for (const p of pages) {
    if (p.parsed.frontmatter.type !== "source") continue;
    const refs = [...(p.parsed.frontmatter.sources ?? []).flatMap((s) => (/\[\[/.test(s) ? extractLinks(s) : [s])), ...extractLinks(p.parsed.body)];
    for (const r of refs) {
      if (resolve(r) !== "source") continue;
      const key = r.replace(/\.md$/i, "").replace(/^raw\//i, "").trim().toLowerCase();
      const name = byLower.get(key);
      if (!name) continue;
      const list = cited.get(name) ?? [];
      if (!list.includes(p.title)) list.push(p.title);
      cited.set(name, list);
    }
  }
  return cited;
}

/**
 * index.md is derived from page frontmatter on every mutation, so it can never drift from
 * the pages. Grouped by page type, one line per page.
 */
export async function rebuildIndex(sb: Sandbox): Promise<void> {
  const pages = await sb.readPages();
  const sources = await sb.sourceNames();
  const groups = new Map<string, PageInfo[]>();
  for (const p of pages) {
    const t = PAGE_TYPES.includes(p.parsed.frontmatter.type as never) ? (p.parsed.frontmatter.type as string) : "other";
    groups.set(t, [...(groups.get(t) ?? []), p]);
  }
  const out: string[] = [
    "# Index",
    "",
    `> Generated by the wiki server after every change — do not edit by hand. ${pages.length} pages, ${sources.length} raw sources.`,
    "",
  ];
  for (const t of [...PAGE_TYPES, "other"]) {
    const list = groups.get(t);
    if (!list?.length) continue;
    out.push(`## ${TYPE_HEADINGS[t] ?? "Other (missing or unknown type)"}`, "");
    for (const p of list) {
      const summary = (p.parsed.frontmatter.summary ?? "").toString().replace(/\s+/g, " ").trim();
      out.push(`- [[${p.title}]]${summary ? ` — ${summary}` : ""}`);
    }
    out.push("");
  }
  if (sources.length) {
    const cited = citedSources(pages, sources);
    out.push("## Raw sources", "");
    for (const s of sources) {
      const by = cited.get(s);
      out.push(`- [[raw/${s}]] — ${by ? `summarized in ${by.map((t) => `[[${t}]]`).join(", ")}` : "not ingested yet"}`);
    }
    out.push("");
  }
  await atomicWrite(path.join(sb.dir, "index.md"), out.join("\n"));
}

export type LogOp = "ingest" | "query" | "lint" | "note" | "create" | "edit" | "delete" | "add-source" | "start";

function stamp(d = new Date()): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

/** Append one entry in the gist's greppable format: `## [YYYY-MM-DD HH:mm] op | title`. */
export async function appendLog(sb: Sandbox, op: LogOp, title: string, details?: string): Promise<void> {
  const oneLine = title.replace(/\s+/g, " ").trim();
  const body = details?.trim() ? `\n${details.trim()}\n` : "";
  const file = path.join(sb.dir, "log.md");
  await assertNotSymlink(file, "file");
  await fs.appendFile(file, `\n## [${stamp()}] ${op} | ${oneLine}\n${body}`, "utf8");
}

export async function recentLog(sb: Sandbox, n: number): Promise<string[]> {
  let text: string;
  try {
    text = await fs.readFile(path.join(sb.dir, "log.md"), "utf8");
  } catch {
    return [];
  }
  return text
    .split("\n")
    .filter((l) => l.startsWith("## ["))
    .slice(-n)
    .map((l) => l.slice(3));
}
